function hash(s: string): number {
  let h = 2166136261;
  for (const c of s) {
    h ^= c.charCodeAt(0);
    h = Math.imul(h, 16777619);
  }
  return h >>> 0;
}

/** Défi du jour : le même pour tout le monde à une date donnée. `offset` sert à « tirer un autre défi ». */
export function defiOfDay(day: string, offset = 0, list: string[] = DEFIS): string {
  return list[(hash(day) + offset * 7919) % list.length];
}
